const BUILTIN_COLLECTIONS: readonly LearningV2ReadingCollectionKey[] = [
  'youth', 'adult', 'subject', 'vision', 'knowledge',
];

function inferCollections(entry: ReadingSeed): readonly LearningV2ReadingCollectionKey[] {
  const explicit = entry.collections || [];
  const inferred = new Set<LearningV2ReadingCollectionKey>(explicit);
  if (entry.readingMode === 'builtin') {
    if (entry.language === 'en') {
      inferred.add('youth');
      inferred.add('adult');
      inferred.add('vision');
    } else if (entry.category === 'classics' || entry.category === 'zhiguai') {
      inferred.add('youth');
      inferred.add('adult');
      inferred.add('history');
    } else {
      inferred.add('knowledge');
      inferred.add('subject');
    }
  }
  if (entry.id.startsWith('subject-') || (entry.collections || []).includes('subject')) {
    inferred.add('subject');
  }
  if (entry.id.includes('red') || entry.id === 'knowledge-red-history-guide') inferred.add('red');
  if (entry.id.includes('history') || entry.category === 'classics') inferred.add('history');
  if (entry.id.includes('science') || entry.id.includes('origin') || entry.id.includes('relativity')) inferred.add('science');
  if (entry.id.includes('trivia')) inferred.add('trivia');
  if (entry.id.startsWith('knowledge-')) inferred.add('knowledge');
  if (entry.category === 'science') {
    inferred.add('science');
    inferred.add('knowledge');
    inferred.add('subject');
  }
  if (entry.category === 'common-sense') {
    inferred.add('knowledge');
    inferred.add('youth');
    inferred.add('adult');
  }
  if (entry.category === 'world-records') {
    inferred.add('trivia');
    inferred.add('knowledge');
    inferred.add('vision');
  }
  if (entry.category === 'trivia') {
    inferred.add('trivia');
    inferred.add('knowledge');
    inferred.add('vision');
  }
  return [...inferred];
}

export const LEARNING_V2_READING_CATALOG: readonly LearningV2ReadingEntry[] = READING_CATALOG_SEED.map((seed) => {
  const override = BUILTIN_READING_OVERRIDES[seed.id] || {};
  const normalized: ReadingSeed = { ...seed, ...override };
  return {
    ...normalized,
    collections: inferCollections(normalized),
    subjects: READING_SUBJECTS[seed.id] || normalized.subjects || [],
    readingMode: normalized.readingMode || (normalized.category === 'web-novel' ? 'platform' : 'external'),
    language: normalized.language || (/[A-Za-z]{8,}/.test(normalized.title) ? 'en' : 'zh-Hans'),
    annotations: normalized.annotations || [],
    chapterCount: normalized.chapterCount,
    edition: normalized.edition || (normalized.readingMode === 'builtin' ? '内置离线校读版' : undefined),
  };
});

