import { MEDICINE_CURATED_PLANS, MEDICINE_LESSONS } from '../medicine.js';
import type {
  LearningV2CuratedCoursePlan,
  LearningV2LessonStep,
} from '../v2-types.js';
import type { CuratedCoursePlanPatchMap } from './types.js';

type SixBodies = readonly [
  string,
  string,
  string,
  string,
  string,
  string,
];

function buildPatch(
  courseTitle: string,
  bodies: SixBodies,
): Partial<LearningV2CuratedCoursePlan> {
  const lesson = MEDICINE_LESSONS.find((item) => item.title === courseTitle);
  if (!lesson) throw new Error(`Unknown medicine course title: ${courseTitle}`);
  const courseName = lesson.courseName;
  const key = `medicine:${courseName}`;
  const plan = MEDICINE_CURATED_PLANS[key];
  if (!plan) throw new Error(`Missing medicine base course: ${key}`);
  if (plan.steps.length !== bodies.length) {
    throw new Error(`Unexpected medicine step count for ${key}: ${plan.steps.length}`);
  }

  const steps: LearningV2LessonStep[] = plan.steps.map((step, index) => ({
    ...step,
    body: bodies[index]!,
  }));
  return { steps };
}

