import type { CuratedCoursePlanMap, CuratedCoursePlanPatchMap } from './types.js';

type StepAdditions = Readonly<Partial<Record<number, string>>>;

const BASE_PLANS: CuratedCoursePlanMap = ARTS_HUMANITIES_REMAINING_CURATED_PLANS;
const REVIEW_PATCHES: CuratedCoursePlanPatchMap = FOUNDATION_REVIEW_QUALITY_PATCHES;

function deepen(key: string, additions: StepAdditions): readonly LearningV2LessonStep[] {
  const steps = REVIEW_PATCHES[key]?.steps ?? BASE_PLANS[key]?.steps;
  if (!steps) {
    throw new Error(`Depth patch has no source course: ${key}`);
  }
  return steps.map((step, index) => {
    const addition = additions[index];
    return addition === undefined ? step : { ...step, body: `${step.body} ${addition}` };
  });
}

