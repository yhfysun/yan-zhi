const q = (
  prompt: string,
  correct: string,
  distractors: readonly [string, string, string],
  answer: number,
  explanation: string,
  focus: string,
): LearningV2Practice => {
  const options = [...distractors];
  options.splice(answer, 0, correct);
  const closing = EXPLANATION_CLOSINGS[prompt.length % EXPLANATION_CLOSINGS.length];
  return { prompt, options, answer, explanation: `${explanation}${closing}`, focus };
};

const point = (label: LearningV2StudyPoint['label'], text: string, stepIndex: number): LearningV2StudyPoint =>
  ({ label, text, stepIndex });

const src = (id: string, title: string, issuer: string, url: string, usedFor: string) =>
  ({ id, title, issuer, url, usedFor });

type CoursePatch = NonNullable<CuratedCoursePlanPatchMap[string]>;
const withStepClosings = (course: CoursePatch, closings: readonly string[]): CoursePatch => ({
  ...course,
  steps: course.steps?.map((step, index) => ({
    ...step,
    body: `${step.body}${closings[index % closings.length]}`,
  })),
});

