type BodySet = readonly [string, string, string, string, string];
type Seed = Omit<LearningV2CuratedCoursePlan, 'contentStatus' | 'steps' | 'quiz' | 'studyPoints'> & {
  readonly name: string;
  readonly bodies: BodySet;
  readonly points: readonly LearningV2StudyPoint[];
  readonly quiz: readonly LearningV2Practice[];
};

const p = (label: LearningV2StudyPoint['label'], text: string, stepIndex: number): LearningV2StudyPoint => ({ label, text, stepIndex });
const q = (prompt: string, correct: string, wrong: readonly [string, string, string], answer: number, explanation: string, focus: string): LearningV2Practice => {
  const options = [...wrong];
  options.splice(answer, 0, correct);
  return {
    prompt,
    options,
    answer,
    explanation: `${explanation}，并回到原文篇目、底本、注疏来源、版本异文和现代转述边界逐项核对。`,
    focus,
  };
};
