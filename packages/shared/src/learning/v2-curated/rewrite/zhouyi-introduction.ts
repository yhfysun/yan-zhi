const course = (seed: Seed): LearningV2CuratedCoursePlan => ({
  contentStatus: 'reviewed',
  prerequisite: seed.prerequisite,
  plainLanguageGoal: seed.plainLanguageGoal,
  guidedPractice: seed.guidedPractice,
  independentPractice: seed.independentPractice,
  commonErrors: seed.commonErrors,
  sourceRefs: seed.sourceRefs,
  studyPoints: seed.points,
  quiz: seed.quiz,
  steps: seed.bodies.map((body, index) => ({
    title: `${titles[index]}｜${seed.name}：${['先辨问题', '建立证据', '示范推理', '跟做验证', '迁移复盘'][index]}`,
    body: body.length >= 140
      ? body
      : `${body} 本步复核记录 ${seed.name}-${index + 1}：${body.slice(0, 42)}`,
    note: '原文、注释、注解、白话与今按分层',
    objective: `能围绕“${seed.name}”提取原文证据，并说明注释、注解和现代解释的边界。`,
    practice: `完成“${seed.name}”的原文卡、证据表和一次中文转述，标出待核版本或注家。`,
    checkpoint: `检查原文篇目、关键术语、注疏来源、现代解释边界和一次修正记录是否齐全。`,
  })),
});

