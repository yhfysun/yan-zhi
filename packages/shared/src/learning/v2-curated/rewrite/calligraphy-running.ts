const q = (
  prompt: string,
  correct: string,
  distractors: readonly [string, string, string],
  answer: number,
  explanation: string,
  focus: string,
): LearningV2Practice => {
  const options = [...distractors];
  options.splice(answer, 0, correct);
  const closing = EXPLANATION_CLOSINGS[prompt.length % EXPLANATION_CLOSINGS.length];
  return { prompt, options, answer, explanation: `${explanation}${closing}`, focus };
};

const point = (label: LearningV2StudyPoint['label'], text: string, stepIndex: number): LearningV2StudyPoint =>
  ({ label, text, stepIndex });

