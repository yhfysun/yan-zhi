let nextAnswerIndex = 0;

const q = (
  prompt: string,
  correct: string,
  distractors: readonly [string, string, string],
  answer: number,
  explanation: string,
  focus: string,
): LearningV2Practice => {
  const answerIndex = (nextAnswerIndex + answer) % 4;
  nextAnswerIndex += 1;
  const options = [...distractors];
  options.splice(answerIndex, 0, correct);
  return { prompt, options, answer: answerIndex, explanation, focus };
};

