const EARLIER_DEPTH_PATCHES: CuratedCoursePlanPatchMap = {
  ...LANGUAGE_DEPTH_PATCHES,
  ...STEM_DEPTH_PATCHES,
};

const BASE_PLANS: CuratedCoursePlanMap = Object.fromEntries(
  Object.entries({
    ...CURRENT_COURSE_CURATED_PLANS,
    ...ADVANCED_HUMANITIES_CURATED_PLANS,
    ...ADVANCED2_HUMANITIES_CURATED_PLANS,
    ...ADVANCED_LANGUAGES_CULTURE_CURATED_PLANS,
    ...MILESTONE_LANGUAGES_CULTURE_CURATED_PLANS,
    ...PRACTICAL_CULTURE_CURATED_PLANS,
    ...PRIORITY_EXPANSION_CURATED_PLANS,
    ...SECURITY_CURATED_PLANS,
    ...MEDICINE_CURATED_PLANS,
  }).map(([key, plan]) => {
    const earlierPatch = EARLIER_DEPTH_PATCHES[key];
    return [key, earlierPatch ? { ...plan, ...earlierPatch } : plan];
  }),
);

function deepen(
  key: string,
  replacements: Readonly<Record<string, string>>,
): readonly LearningV2LessonStep[] {
  const plan = BASE_PLANS[key];
  if (!plan) throw new Error(`Missing professional depth base course: ${key}`);

  const matched = new Set<string>();
  const steps = plan.steps.map((step) => {
    const body = replacements[step.title];
    if (!body) return step;
    matched.add(step.title);
    return { ...step, body };
  });

  const unknownTitles = Object.keys(replacements).filter((title) => !matched.has(title));
  if (unknownTitles.length > 0) {
    throw new Error(`Unknown step titles in ${key}: ${unknownTitles.join(', ')}`);
  }

  const remaining = steps.filter((step) => step.body.length < 100);
  if (remaining.length > 0) {
    throw new Error(
      `Professional depth left short steps in ${key}: ${remaining.map((step) => step.title).join(', ')}`,
    );
  }
  return steps;
}

function medicinePatch(courseName: string, body: string) {
  const key = `medicine:${courseName}`;
  return {
    steps: deepen(key, {
      建立时间轴与观察表: body,
    }),
  };
}

