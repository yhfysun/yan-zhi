type AiStageExamples = readonly (readonly LearningV2LessonExample[])[];

function attachAiExamples(
  courses: readonly ProgrammingCourseSeed[],
  stageExamples: AiStageExamples,
): readonly ProgrammingCourseSeed[] {
  return courses.map((course, courseIndex) => {
    const courseExamples = stageExamples[courseIndex] ?? [];
    return {
      ...course,
      steps: course.steps.map((step, stepIndex) => {
        const example = courseExamples[stepIndex];
        return example ? [step[0], step[1], step[2], example] as const : step;
      }),
    };
  });
}

