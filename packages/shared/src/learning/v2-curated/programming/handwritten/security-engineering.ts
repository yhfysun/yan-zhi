const attachSecurityExamples = (
  courses: readonly ProgrammingCourseSeed[],
  examples: Readonly<Record<string, readonly LearningV2LessonExample[]>>,
): readonly ProgrammingCourseSeed[] => courses.map((course) => {
  const courseExamples = examples[course.name];
  if (!courseExamples || courseExamples.length !== course.steps.length) {
    throw new Error(`security examples missing for ${course.name}`);
  }
  return {
    ...course,
    steps: course.steps.map((step, index) => [step[0], step[1], step[2], courseExamples[index]] as const),
  };
});

