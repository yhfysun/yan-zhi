type StepBodies = Readonly<Partial<Record<number, string>>>;

function patchSteps(
  steps: readonly LearningV2LessonStep[],
  bodies: StepBodies,
): readonly LearningV2LessonStep[] {
  return steps.map((step, index) => {
    const body = bodies[index];
    return body === undefined ? step : { ...step, body };
  });
}

