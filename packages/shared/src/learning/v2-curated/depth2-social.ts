function resolvedBaseSteps(key: string): readonly LearningV2LessonStep[] {
  const plan = BASE_PLANS[key];
  if (!plan) throw new Error(`Missing social depth2 base course: ${key}`);

  return plan.steps.map((step, index) => {
    const finalStep = index === plan.steps.length - 1;
    const independentStep = index === plan.steps.length - 2;
    const guidedStep = index === 2;
    const lead = step.body
      .trim()
      .split(/[。！？]/)
      .find((segment) => segment.trim().length > 0)
      ?.trim()
      || step.note
      || step.title;
    const excerpt = lead.length > 96 ? `${lead.slice(0, 96)}…` : lead;
    const coursePractice = guidedStep
      ? plan.guidedPractice
      : independentStep || finalStep
        ? plan.independentPractice
        : plan.guidedPractice;

    return {
      ...step,
      objective: step.objective ?? `${step.title}：${excerpt}`,
      practice: step.practice ?? `${coursePractice} 本步聚焦“${step.title}”：${excerpt}`,
      checkpoint: step.checkpoint
        ?? `检查“${step.title}”：${step.note || excerpt}。再给出一个反例、失败条件或能证伪当前结论的证据。`,
    };
  });
}

function extendedSteps(
  key: string,
  additions: Readonly<Record<number, string>>,
): readonly LearningV2LessonStep[] {
  const plan = BASE_PLANS[key];
  if (!plan) throw new Error(`Missing social depth2 base course: ${key}`);
  const resolvedSteps = resolvedBaseSteps(key);

  const shortIndices = plan.steps.flatMap((step, index) =>
    step.body.trim().length < 100 ? [index] : [],
  );
  const replacedIndices = Object.keys(additions)
    .map(Number)
    .sort((left, right) => left - right);

  if (
    shortIndices.length !== replacedIndices.length
    || shortIndices.some((index, position) => index !== replacedIndices[position])
  ) {
    throw new Error(
      `Social depth2 short-step mismatch: ${key} expected [${shortIndices}], got [${replacedIndices}]`,
    );
  }

  return resolvedSteps.map((step, index) => {
    const addition = additions[index];
    if (addition === undefined) return step;
    const body = `${step.body.trim()}${addition}`;
    if (body.length < 100 || body.length > 170) {
      throw new Error(
        `Social depth2 body length out of range: ${key}[${index}] = ${body.length}`,
      );
    }
    return { ...step, body };
  });
}

const patch = (
  key: string,
  additions: Readonly<Record<number, string>>,
): { readonly steps: readonly LearningV2LessonStep[] } => ({
  steps: extendedSteps(key, additions),
});

