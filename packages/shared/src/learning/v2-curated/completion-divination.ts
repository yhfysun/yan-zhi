import type { LearningV2CuratedCoursePlan } from '../v2-types.js';
import type { CuratedCoursePlanMap } from './types.js';

type StepSeed = readonly [title: string, body: string, note: string];

function plan(
  prerequisite: string,
  plainLanguageGoal: string,
  guidedPractice: string,
  independentPractice: string,
  commonErrors: readonly string[],
  sourceRefs: readonly string[],
  steps: readonly StepSeed[],
): LearningV2CuratedCoursePlan {
  return {
    prerequisite,
    plainLanguageGoal,
    guidedPractice,
    independentPractice,
    commonErrors,
    sourceRefs,
    steps: steps.map(([title, body, note]) => ({ title, body, note })),
  };
}

