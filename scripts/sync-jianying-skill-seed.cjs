// 从 `.claude/skills/jianying-editing/SKILL.md`（唯一真相源）生成 skill 的 references 文件种子：
//   apps/server/src/skills/jianying-editing-files.generated.ts
//
// ★ 为什么要生成而不是手抄：db.ts 里的 skill 正文有 2000 字预算（超了静默截断），
//   细则必须下沉到 filesJson；手抄两份必然漂移。仓库树是唯一真相源，种子由它生成，
//   `apps/server/test/clip-jianying.test.ts` 会逐字回读校验（改了 md 忘了跑本脚本 → 测试红）。
// 用法：node scripts/sync-jianying-skill-seed.cjs
const fs = require('fs');
const path = require('path');

const SRC = path.resolve(__dirname, '..', '.claude', 'skills', 'jianying-editing', 'SKILL.md');
const OUT = path.resolve(__dirname, '..', 'apps', 'server', 'src', 'skills', 'jianying-editing-files.generated.ts');

/** 换行统一 LF：git 入库把 CRLF 归一成 LF，种子必须与入库后的内容一致 */
function toLF(s) { return s.split('\r\n').join('\n'); }

/** 去掉 YAML frontmatter（name/description 由 skill 种子字段承载） */
function stripFrontmatter(s) {
  const m = s.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n/);
  return m ? s.slice(m[0].length) : s;
}

const md = toLF(fs.readFileSync(SRC, 'utf8'));
const content = stripFrontmatter(md).trim() + '\n';
const files = [{ path: 'references/jianying-playbook.md', content }];

const header = [
  '// AUTO-GENERATED by scripts/sync-jianying-skill-seed.cjs —— 不要手改，改 .claude/skills/jianying-editing/SKILL.md 后重跑脚本。',
  '// 用途：db.ts 的 skill_jianying_editing 种子把这份内容写进 filesJson，运行时落到工作目录供 file_read。',
].join('\n');
const out = `${header}\nexport const JIANYING_SKILL_FILES: Array<{ path: string; content: string }> = ${JSON.stringify(files, null, 2)};\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');

// 回读校验：把生成的字面量解析回来，逐字比对（任一步不符即非零退出）
const generated = fs.readFileSync(OUT, 'utf8');
const marker = 'export const JIANYING_SKILL_FILES: Array<{ path: string; content: string }> = ';
const start = generated.indexOf(marker);
if (start < 0) { console.error('生成文件缺少导出标记'); process.exit(1); }
const literal = generated.slice(start + marker.length).trim().replace(/;$/, '');
const parsed = JSON.parse(literal);
if (JSON.stringify(parsed) !== JSON.stringify(files)) {
  console.error('回读校验失败：生成内容与源文件不一致');
  process.exit(1);
}
console.log(`已生成 ${path.relative(process.cwd(), OUT)}（${content.length} 字符）`);
