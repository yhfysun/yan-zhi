#!/usr/bin/env node
/**
 * Generate the production Learning V2 catalog from the reviewed prototype data.
 *
 * The prototype remains the design review source. This script strips browser-only
 * helpers and writes a typed, importable catalog shared by desktop, web and mobile.
 */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const ROOT = path.resolve(__dirname, '..');
const sourcePath = path.join(ROOT, 'docs', 'prototypes', 'learning-redesign-v2', 'prototype-data.js');
const targetDir = path.join(ROOT, 'packages', 'shared', 'src', 'learning');
const targetPath = path.join(targetDir, 'v2-catalog.ts');

const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(sourcePath, 'utf8'), context, { filename: sourcePath });

const data = context.window.LEARNING_PROTOTYPE;
if (!data || !Array.isArray(data.subjects) || !Array.isArray(data.pages)) {
  throw new Error('prototype-data.js did not expose LEARNING_PROTOTYPE');
}

const json = JSON.stringify(data, null, 2);
const output = `// AUTO-GENERATED by scripts/generate-learning-v2-catalog.cjs\n// Source: docs/prototypes/learning-redesign-v2/prototype-data.js\n/* eslint-disable */\nexport const LEARNING_V2_RAW_CATALOG = ${json} as const;\n`;

fs.mkdirSync(targetDir, { recursive: true });
fs.writeFileSync(targetPath, output, 'utf8');
console.log(`generated ${path.relative(ROOT, targetPath)} (${data.subjects.length} subjects, ${data.pages.length} pages)`);
