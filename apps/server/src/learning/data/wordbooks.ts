const TOPIC_SOURCE_WORDS = (() => {
  const byWord = new Map<string, BuiltinWordEntry>();
  for (const pack of Object.values(FULL_PACKS)) {
    for (const entry of pack.words) {
      const key = entry.word.trim().toLowerCase();
      if (!key || byWord.has(key)) continue;
      byWord.set(key, entry);
    }
  }
  return [...byWord.values()];
})();

