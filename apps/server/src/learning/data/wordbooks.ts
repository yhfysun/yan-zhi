type WordRow = [word: string, gloss: string];
function addWordRows(target: BuiltinWordEntry[], rows: WordRow[]) {
  const seen = new Set(target.map((entry) => entry.word.trim().toLowerCase()));
  for (const [word, gloss] of rows) {
    const key = word.trim().toLowerCase();
    if (!key || seen.has(key)) continue;
    seen.add(key);
    target.push({ word, gloss });
  }
}

