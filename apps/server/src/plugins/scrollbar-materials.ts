/**
 * 每套皮肤的金箍棒材质配色（2026-09-13 用户要求「多搞几个样式配色？每个皮肤一个？」）。
 *
 * 设计原则：
 *   ① 金箍棒的本体是「金属箍 + 棍身」，所以每套都保留 [箍带][棍身] 的双材质结构，
 *      皮肤只改**材质颜色**（金 → 玉/银/铜/霓虹/朱砂/竹青…），不改结构 ——
 *      结构一致才能保证横竖观感统一、也不破坏"这是根棒子"的识别度。
 *   ② 配色与皮肤主题语义挂钩（不是随便挑色）：
 *      樱夜→樱粉玉金 / 赛博→霓虹钨钢 / 竹雨→竹青黄铜 / 太极→黑白玉 / 敦煌→朱砂鎏金 …
 *   ③ 每色 5 档：edge(极暗) dark mid light hi(高光)。
 *      - edge 决定圆柱收边，必须够暗，否则 8px 厚度上会"发糊"；
 *      - hi 是 45% 处的那道高光，决定金属感强弱，饱和度别拉满。
 *   ④ 棍身一般用同一色系的深色版本（比箍带暗 2~3 档），形成"箍亮身暗"的对比 ——
 *      这是金箍棒最核心的视觉特征，每套都要保住。
 */

/** 材质配色：{ cap: 箍带, body: 棍身 } */
export type ScrollbarMaterial = {
  cap: { edge: string; dark: string; mid: string; light: string; hi: string };
  body: { edge: string; dark: string; mid: string; light: string; hi: string };
};

/** 由「亮色」和「暗色」快速推出一套金属 5 档（手工微调过，比机械调亮更耐看） */
function mat(
  capEdge: string, capDark: string, capMid: string, capLight: string, capHi: string,
  bodyEdge: string, bodyDark: string, bodyMid: string, bodyLight: string, bodyHi: string,
): ScrollbarMaterial {
  return {
    cap: { edge: capEdge, dark: capDark, mid: capMid, light: capLight, hi: capHi },
    body: { edge: bodyEdge, dark: bodyDark, mid: bodyMid, light: bodyLight, hi: bodyHi },
  };
}

