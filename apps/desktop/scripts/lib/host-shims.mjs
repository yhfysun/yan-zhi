/**
 * 宿主共享依赖 shim 生成（mode-pluginization P0）。
 *
 * 生成两类静态 ESM shim，全部委托回宿主注入的全局：
 *  · host-shims/vue.mjs 等 —— 渲染层用：插件前端 bundle 对 vue/element-plus 等的 import
 *    在构建期被改写到 yz://shared/<key>.mjs，shim 读 window.__YZ_HOST__.m[key]（宿主
 *    initPluginHostBridge 挂载）。命名导出清单从真实模块枚举 —— 插件 bundle 只会被
 *    rollup 引用到真实存在的导出，shim 全量枚举即可覆盖。
 *  · host-shims/__server-host__.mjs —— 插件后端 bundle 用：esbuild 把 *host-bridge.js 的
 *    import 重定向到本 shim，读 globalThis.__YZ_SERVER_HOST__（服务端 injectServerHostBridge
 *    注入）。导出名从 apps/server/src/host-bridge.ts 静态解析。
 *
 * ★ 完备性由 apps/desktop/test/host-shims.test.cjs 守门：每个 shim 的每个导出运行时非 undefined。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** 渲染层共享依赖（key 与 packages/ui/src/plugin-host-bridge.ts 的 SHARED_KEYS 一致） */
export const SHARED_MODULES = [
  { key: 'vue', specifier: 'vue' },
  { key: 'vueRouter', specifier: 'vue-router' },
  { key: 'pinia', specifier: 'pinia' },
  { key: 'elementPlus', specifier: 'element-plus' },
  { key: 'elementPlusIcons', specifier: '@element-plus/icons-vue' },
];

export function shimsDir(desktopDir) {
  return path.join(desktopDir, 'host-shims');
}

// ESM 导出名必须是合法标识符；这些键即使出现在命名空间里也不能写进 shim
const RESERVED = new Set([
  'default', 'await', 'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'delete',
  'do', 'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if',
  'implements', 'import', 'in', 'instanceof', 'interface', 'let', 'new', 'null', 'package',
  'private', 'protected', 'public', 'return', 'static', 'super', 'switch', 'this', 'throw',
  'true', 'try', 'typeof', 'var', 'void', 'while', 'with', 'yield',
]);
const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function shimBanner(kind) {
  return (
    `// AUTO-GENERATED by apps/desktop/scripts/generate-host-shims.mjs —— 不要手改。\n` +
    `// ${kind}\n` +
    `// 重新生成: pnpm --filter @yan-zhi/desktop generate:host-shims\n`
  );
}

function sharedShimSource(key, specifier, names) {
  return (
    shimBanner(`渲染层共享依赖 shim：${specifier} → window.__YZ_HOST__.m.${key}`) +
    `const __m = globalThis.__YZ_HOST__ && globalThis.__YZ_HOST__.m && globalThis.__YZ_HOST__.m[${JSON.stringify(key)}];\n` +
    `if (!__m) throw new Error('[yz-shim] window.__YZ_HOST__ 未注入（宿主桥缺失或插件先于宿主装载）');\n` +
    `export default __m;\n` +
    names.map((n) => `export const ${n} = __m[${JSON.stringify(n)}];`).join('\n') +
    `\n`
  );
}

function serverShimSource(names) {
  return (
    shimBanner('插件后端宿主桥 shim：*host-bridge.js → globalThis.__YZ_SERVER_HOST__') +
    `const __h = globalThis.__YZ_SERVER_HOST__;\n` +
    `if (!__h) throw new Error('[yz-shim] globalThis.__YZ_SERVER_HOST__ 未注入（服务端未注入插件宿主桥）');\n` +
    `export default __h;\n` +
    names.map((n) => `export const ${n} = __h[${JSON.stringify(n)}];`).join('\n') +
    `\n`
  );
}

/** 从宿主桥 TS 源解析导出名（const/let/var/function/class/ 解构 re-export/ 花括号 re-export） */
export function parseHostBridgeExports(source) {
  const names = new Set();
  const declRe = /export\s+(?:declare\s+)?(?:const|let|var|function|async\s+function|class)\s+([A-Za-z_$][\w$]*)/g;
  for (const m of source.matchAll(declRe)) names.add(m[1]);
  // export const { a, b, type T } = mod; —— 解构转发（path-guard 整面收编用）
  const destructureRe = /export\s+const\s*\{([^}]+)\}\s*=/g;
  for (const m of source.matchAll(destructureRe)) {
    for (const part of m[1].split(',')) {
      const seg = part.trim();
      if (!seg || seg.startsWith('type ')) continue;
      const name = seg.split(/\s+as\s+/).pop().trim();
      if (name) names.add(name);
    }
  }
  const braceRe = /export\s*\{([^}]+)\}/g;
  for (const m of source.matchAll(braceRe)) {
    for (const part of m[1].split(',')) {
      const name = part.trim().split(/\s+as\s+/).pop().trim();
      if (name) names.add(name);
    }
  }
  return [...names].filter((n) => IDENT_RE.test(n) && !RESERVED.has(n)).sort();
}

/**
 * 生成全部 shim。返回 { dir, shared: [{key, specifier, names}], serverHost: {names} }。
 * 幂等：内容不变时不重写（利于增量构建）。
 */
export async function generateHostShims(desktopDir, opts = {}) {
  const dir = shimsDir(desktopDir);
  fs.mkdirSync(dir, { recursive: true });
  const shared = [];
  for (const { key, specifier } of SHARED_MODULES) {
    const mod = opts.mockModules?.[key] || (await import(specifier));
    const names = Object.keys(mod).filter((n) => IDENT_RE.test(n) && !RESERVED.has(n)).sort();
    shared.push({ key, specifier, names });
    writeFileIfChanged(path.join(dir, `${key}.mjs`), sharedShimSource(key, specifier, names));
  }

  // 服务端宿主桥 shim：导出名来自 host-bridge.ts 静态解析
  const hostBridgeSrc =
    opts.hostBridgeSource ??
    fs.readFileSync(path.join(desktopDir, '..', 'server', 'src', 'host-bridge.ts'), 'utf8');
  const serverNames = parseHostBridgeExports(hostBridgeSrc);
  writeFileIfChanged(path.join(dir, '__server-host__.mjs'), serverShimSource(serverNames));

  writeFileIfChanged(
    path.join(dir, 'manifest.json'),
    JSON.stringify(
      {
        generatedBy: 'apps/desktop/scripts/generate-host-shims.mjs',
        hostApiVersion: 1,
        shared: shared.map((s) => ({ key: s.key, specifier: s.specifier, exportCount: s.names.length })),
        serverHostExports: serverNames,
      },
      null,
      2,
    ) + '\n',
  );
  return { dir, shared, serverHost: { names: serverNames } };
}

function writeFileIfChanged(file, content) {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return false;
  } catch {
    /* 首次生成 */
  }
  fs.writeFileSync(file, content, 'utf8');
  return true;
}

/** CLI 直跑入口（generate-host-shims.mjs 包装调用；被 import 时不执行） */
export async function main() {
  const libDir = path.dirname(fileURLToPath(import.meta.url)); // apps/desktop/scripts/lib
  const desktopDir = path.resolve(libDir, '..', '..'); // apps/desktop
  const { shared, serverHost } = await generateHostShims(desktopDir);
  for (const s of shared) console.log(`[host-shims] ${s.specifier} → ${s.key}.mjs（${s.names.length} 导出）`);
  console.log(`[host-shims] server-host shim（${serverHost.names.length} 导出）`);
}
